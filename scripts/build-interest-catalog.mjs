// Writes the catalogue data section of supabase/migrations/0017_interest_catalog.sql from
// supabase/catalog/interest-catalog.tsv (label<TAB>node_id<TAB>existing|new, A-Z). Run: node scripts/build-interest-catalog.mjs
// Checks before writing: ids are well-formed level-3/4 slugs, labels and ids are unique, the file is A-Z.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const tsvPath = join(root, 'supabase', 'catalog', 'interest-catalog.tsv');
const sqlPath = join(root, 'supabase', 'migrations', '0017_interest_catalog.sql');
const BEGIN = '-- BEGIN CATALOGUE DATA (generated by scripts/build-interest-catalog.mjs; edit the TSV, not this block)';
const END = '-- END CATALOGUE DATA';

export const parseCatalog = (text) => text.split('\n').filter((line) => line && !line.startsWith('#')).map((line) => {
  const [label, id, kind] = line.split('\t');
  return { label, id, kind };
});

export const checkCatalog = (rows) => {
  const problems = [];
  const ids = new Set();
  const labels = new Set();
  rows.forEach((row, i) => {
    if (!/^[a-z0-9_]+(\.[a-z0-9_]+){2,3}$/.test(row.id || '')) problems.push(`line ${i + 1}: bad id ${row.id}`);
    if (!row.label?.trim()) problems.push(`line ${i + 1}: empty label`);
    if (!['existing', 'new'].includes(row.kind)) problems.push(`line ${i + 1}: kind must be existing or new`);
    if (ids.has(row.id)) problems.push(`duplicate id ${row.id}`);
    if (labels.has(row.label.toLowerCase())) problems.push(`duplicate label ${row.label}`);
    if (i && rows[i - 1].label.toLowerCase() > row.label.toLowerCase()) problems.push(`not A-Z at ${row.label}`);
    ids.add(row.id);
    labels.add(row.label.toLowerCase());
  });
  return problems;
};

const q = (s) => `'${s.replace(/'/g, "''")}'`;
export const catalogSql = (rows) => [
  BEGIN,
  'insert into pg_temp.brivia_catalog_0017 (id, label, ord) values',
  rows.map((row, i) => `  (${q(row.id)}, ${q(row.label)}, ${i + 1})`).join(',\n') + ';',
  END,
].join('\n');

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const rows = parseCatalog(readFileSync(tsvPath, 'utf8'));
  const problems = checkCatalog(rows);
  if (problems.length) { console.error(problems.join('\n')); process.exit(1); }
  const sql = readFileSync(sqlPath, 'utf8');
  const start = sql.indexOf(BEGIN);
  const stop = sql.indexOf(END);
  if (start < 0 || stop < start) { console.error('0017 has no catalogue data markers'); process.exit(1); }
  writeFileSync(sqlPath, sql.slice(0, start) + catalogSql(rows) + sql.slice(stop + END.length));
  console.log(`0017: ${rows.length} catalogue rows (${rows.filter((r) => r.kind === 'new').length} new).`);
}
