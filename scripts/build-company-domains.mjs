// Builds supabase/migrations/0040_company_icons.sql from supabase/catalog/company-domains.txt (D-148).
// Usage: node scripts/build-company-domains.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const rows = readFileSync('supabase/catalog/company-domains.txt', 'utf8').split('\n')
  .filter((l) => l.includes(' | ') && !l.startsWith('#')).map((l) => l.split(' | ').map((s) => s.trim()));
for (const [name, domain] of rows) if (!/^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$/.test(domain)) throw new Error(`bad domain ${name}: ${domain}`);
const q = (s) => `'${s.replace(/'/g, "''")}'`;
writeFileSync('supabase/migrations/0040_company_icons.sql', `set lock_timeout = '5s';
-- 0040_company_icons.sql: a logo for every company in the founder's directory (founder: "I WANT LOGOS FOR EVERY COMPANY",
-- 2026-11-04, D-148). Generated by scripts/build-company-domains.mjs from supabase/catalog/company-domains.txt.
-- Applied after 0039 (README "## 0040"). 0001-0039 are frozen. Idempotent.
--   1. company.icon_domain: the website a company's square icon is read from. Not unique (a group's names can share a
--      site: Oracle and Oracle Financial Services Software, DMart and Avenue Supermarts), unlike company.domain, which
--      deduplicates organisations and is left as it is.
--   2. The ${rows.length} seeded companies get their official website as icon_domain.
--   3. brivia_companies_needing_icons(limit, offset) and brivia_set_company_icon(id, path): the directory Edge Function's
--      bulk logo pass (service role only): fetch each site's icon once, store it, set logo_path.

alter table public.company add column if not exists icon_domain text
  check (icon_domain is null or icon_domain ~ '^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$');

update public.company c set icon_domain = v.domain
  from (values
${rows.map(([n, d]) => `    (${q(n)}, ${q(d)})`).join(',\n')}
  ) as v(name, domain)
 where c.source = 'admin' and c.name = v.name and c.icon_domain is distinct from v.domain;

create or replace function public.brivia_companies_needing_icons(p_limit int default 30, p_offset int default 0)
returns table(id uuid, icon_domain text)
language sql
stable
security definer
set search_path = public
as $$
  select c.id, coalesce(c.icon_domain, c.domain)
    from public.company c
   where c.logo_path is null and coalesce(c.icon_domain, c.domain) is not null and c.source <> 'member'
   order by c.id
   limit least(greatest(coalesce(p_limit, 30), 1), 60) offset greatest(coalesce(p_offset, 0), 0)
$$;
revoke all on function public.brivia_companies_needing_icons(int, int) from public, anon, authenticated;

create or replace function public.brivia_set_company_icon(p_id uuid, p_path text)
returns void
language sql
volatile
security definer
set search_path = public
as $$
  update public.company set logo_path = p_path
   where id = p_id and logo_path is null and source <> 'member' and p_path ~ '^directory/[A-Za-z0-9._-]{1,80}$'
$$;
revoke all on function public.brivia_set_company_icon(uuid, text) from public, anon, authenticated;
do $$ begin
  if exists (select 1 from pg_roles where rolname = 'service_role') then
    execute 'grant execute on function public.brivia_companies_needing_icons(int, int) to service_role';
    execute 'grant execute on function public.brivia_set_company_icon(uuid, text) to service_role';
  end if;
end $$;
`);
// The same list for the live import (README "## 0040").
writeFileSync('site/public/data/company-domains.json', JSON.stringify(rows));
console.log(`${rows.length} company websites`);
