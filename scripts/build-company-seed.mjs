// Builds supabase/migrations/0039_company_seed.sql from supabase/catalog/companies.txt (D-142).
// Usage: node scripts/build-company-seed.mjs   (0039 is frozen once applied: later lists are new migrations)
import { readFileSync, writeFileSync } from 'node:fs';

const src = readFileSync('supabase/catalog/companies.txt', 'utf8').split('\n');
const fold = (s) => s.normalize('NFKD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/[\s\p{P}\p{S}]+/gu, ' ').trim();
const rows = [];
const seen = new Map();
let industry = '';
for (const raw of src) {
  const line = raw.trim();
  if (!line || line.startsWith('# ')) continue;
  if (line.startsWith('## ')) { industry = line.slice(3).trim(); continue; }
  const key = fold(line);
  if (seen.has(key)) continue;
  seen.set(key, line);
  if (line.length > 80 || industry.length > 40) throw new Error(`too long: ${line} / ${industry}`);
  rows.push([line, industry]);
}
const q = (s) => `'${s.replace(/'/g, "''")}'`;
const sql = `set lock_timeout = '5s';
-- 0039_company_seed.sql: the founder's company directory (${rows.length} organisations in ${new Set(rows.map((r) => r[1])).size} industries; founder request
-- 2026-11-03, D-142), generated by scripts/build-company-seed.mjs from supabase/catalog/companies.txt. Applied by hand
-- after 0038 (README "## 0039"). 0001-0038 are frozen. Idempotent: a name already in the directory is skipped.
--   1. Each organisation is an 'admin', verified row (it ranks first in search). No website or logo yet.
--   2. brivia_cache_companies (0036) now also fills a seeded row: when the directory Edge Function finds the same name
--      on Wikidata and the row has no Wikidata id or website yet, it takes them and the logo, instead of adding a
--      second row. So each seeded company gets its logo the first time a member searches for it.

insert into public.company (name, industry, source, verified)
select v.name, v.industry, 'admin', true
  from (values
${rows.map(([n, i]) => `    (${q(n)}, ${q(i)})`).join(',\n')}
  ) as v(name, industry)
 where not exists (select 1 from public.company c where c.name_key = public.brivia_fold(v.name));

create or replace function public.brivia_cache_companies(p_rows jsonb)
returns setof uuid
language plpgsql
volatile
security definer
set search_path = public
as $$
declare r jsonb; v_id uuid; v_domain text;
begin
  for r in select * from jsonb_array_elements(coalesce(p_rows, '[]'::jsonb)) loop
    continue when coalesce(r->>'name', '') = '' or coalesce(r->>'wikidata_id', '') !~ '^Q[0-9]{1,12}$';
    v_domain := public.brivia_domain(r->>'domain');
    v_id := null;
    select c.id into v_id from public.company c where c.wikidata_id = r->>'wikidata_id';
    if v_id is null and v_domain is not null then select c.id into v_id from public.company c where c.domain = v_domain; end if;
    -- D-142: a seeded (admin) row of the same name with no Wikidata id yet is this company.
    if v_id is null then
      select c.id into v_id from public.company c
       where c.source = 'admin' and c.wikidata_id is null and c.name_key = public.brivia_fold(r->>'name')
       order by c.created_at limit 1;
    end if;
    if v_id is null then
      insert into public.company (name, domain, website, logo_path, industry, country_code, wikidata_id, source)
      values (left(r->>'name', 80), v_domain, case when v_domain is not null then 'https://' || v_domain end,
              nullif(r->>'logo_path', ''), nullif(left(r->>'industry', 40), ''),
              case when r->>'country_code' ~ '^[A-Z]{2}$' then r->>'country_code' end, r->>'wikidata_id', 'directory')
      returning id into v_id;
    else
      update public.company set wikidata_id = coalesce(wikidata_id, r->>'wikidata_id'),
                                domain = coalesce(domain, case when not exists (select 1 from public.company d where d.domain = v_domain) then v_domain end),
                                website = coalesce(website, case when v_domain is not null then 'https://' || v_domain end),
                                logo_path = coalesce(nullif(r->>'logo_path', ''), logo_path),
                                industry = coalesce(industry, nullif(left(r->>'industry', 40), ''))
       where id = v_id and source <> 'member';
    end if;
    return next v_id;
  end loop;
end;
$$;
revoke all on function public.brivia_cache_companies(jsonb) from public, anon, authenticated;
do $$ begin
  if exists (select 1 from pg_roles where rolname = 'service_role') then
    execute 'grant execute on function public.brivia_cache_companies(jsonb) to service_role';
  end if;
end $$;
`;
writeFileSync('supabase/migrations/0039_company_seed.sql', sql);
console.log(`${rows.length} companies (${src.filter((l) => l.trim() && !l.startsWith('#')).length} lines, duplicates dropped)`);
