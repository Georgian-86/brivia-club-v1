create or replace function public.add_member_interest(p_label text)
returns text
language plpgsql
volatile
security definer
set search_path = public
as $$
declare
  uid uuid := auth.uid();
  -- Curly apostrophes (iPhone keyboards) count as straight ones.
  v text := regexp_replace(translate(btrim(coalesce(p_label, '')), E'\u2019\u2018', ''''''), '\s+', ' ', 'g');
  blocked constant text := 'fuck|fucking|shit|cunt|bitch|slut|whore|dick|cock|pussy|porn|porno|nsfw|nude|nudes|sex|sexy|'
    || 'hookup|hookups|onlyfans|escort|escorts|sugar daddy|sugar baby|one night stand|rape|nazi|cocaine|heroin|meth|'
    || 'chutiya|madarchod|bhenchod|behenchod|randi|gandu|bsdk|mc|bc';
  found_id text;
  base text;
  slug text;
  k int := 1;
begin
  -- A profile row is required; locking it serialises one member's calls (the daily cap below).
  perform 1 from public.profiles where id = uid for update;
  if uid is null or not found then
    raise exception 'profile required' using errcode = '42501';
  end if;
  if char_length(v) < 2 or char_length(v) > 40
     or v ~ '[[:cntrl:]!"#$%()*,:;<=>?@\[\\\]^_`{|}~]'                     -- ASCII symbols outside & + - . ' /
     or v ~ '[ -⯿　-〿-︀-️\U0001f000-\U0001ffff]'  -- symbols, emoji
     or v ~ '^[0-9 &+./''-]+$'                                              -- digits and punctuation only
     or lower(v) ~ '(https?|www\.|\.(com|in|net|org|io)\M)'
     or lower(v) ~ ('\m(' || blocked || ')\M')
     or exists (select 1 from public.interest_node n where lower(n.label) = lower(v) and n.sensitive)
     -- a label a moderator retired stays retired (docs/MODERATION.md "Members' own interests")
     or exists (select 1 from public.interest_node n where lower(n.label) = lower(v) and n.status = 'retired') then
    raise exception 'not allowed' using errcode = '22023';
  end if;

  select n.id into found_id
    from public.interest_node n
   where lower(n.label) = lower(v) and n.status = 'active' and n.level >= 3 and not n.sensitive
   order by n.catalog_order nulls last, n.level, n.id
   limit 1;
  if found_id is not null then
    return found_id;
  end if;

  if (select count(*) from public.member_custom_interest m
       where m.member_id = uid and m.created_at > now() - interval '24 hours') >= 5 then
    raise exception 'try again later' using errcode = 'PT429';
  end if;
  -- One writer at a time for new nodes, so two members adding the same label get one node.
  perform pg_advisory_xact_lock(hashtext('brivia.add_member_interest'));
  select n.id into found_id from public.interest_node n
   where n.id like 'member.custom.%' and lower(n.label) = lower(v) and n.status = 'active' limit 1;
  if found_id is not null then
    return found_id;
  end if;
  base := left(btrim(regexp_replace(lower(v), '[^a-z0-9]+', '_', 'g'), '_'), 40);
  if base = '' then
    base := 'i' || left(md5(lower(v)), 10);   -- a label in another script
  end if;
  slug := base;
  while exists (select 1 from public.interest_node n where n.id = 'member.custom.' || slug) loop
    k := k + 1;
    slug := base || '_' || k;
  end loop;
  insert into public.interest_node (id, parent_id, level, label, sensitive)
  values ('member.custom.' || slug, 'member.custom', 3, v, false);
  insert into public.member_custom_interest (member_id, node_id) values (uid, 'member.custom.' || slug);
  return 'member.custom.' || slug;
end;
$$;
revoke all on function public.add_member_interest(text) from public, anon;
grant execute on function public.add_member_interest(text) to authenticated;
